const { chromium } = require("playwright");
let fails = 0; const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fails++; };
(async () => { const br = await chromium.launch(); const pg = await br.newPage({ viewport: { width: 1280, height: 900 } });
  pg.on("dialog", (d) => d.dismiss());
  await pg.addInitScript(() => { localStorage.setItem("site_pw", "fixture-pw"); localStorage.setItem("hw_student", "Test S"); });
  await pg.goto("http://127.0.0.1:8767/index.html?l=V04&p=p3", { waitUntil: "networkidle" });
  await pg.fill("#student", "Test S"); await pg.click('.pick[data-p="p3"]'); await pg.click("#go"); await pg.waitForSelector("#s-solve:not(.hidden)");
  for (let i = 0; i < 60 && !(await pg.textContent("#sv-qn")).startsWith("Вопрос 15 "); i++) await pg.click("#sv-next");
  await pg.waitForTimeout(600);
  const w = await pg.$("#sv-passage .gw");
  ok((await w.getAttribute("aria-expanded")) === "false", "word starts aria-expanded=false");
  await w.focus(); await pg.keyboard.press("Enter"); await pg.waitForTimeout(150);
  ok(await pg.isVisible(".gpop"), "Enter on a focused word opens the card");
  ok((await w.getAttribute("aria-expanded")) === "true", "aria-expanded=true while open");
  const said = await pg.textContent('body > .sr-only[role="status"]');
  ok(/remediate/i.test(said) && /Перевод/.test(said), "live region announces: " + said.slice(0, 70));
  await pg.keyboard.press("Escape"); await pg.waitForTimeout(100);
  ok(!(await pg.isVisible(".gpop")) && (await w.getAttribute("aria-expanded")) === "false", "Escape closes and resets aria-expanded");
  ok(await pg.evaluate(() => document.activeElement && document.activeElement.classList.contains("gw")), "focus stays on the word after Escape");
  await pg.keyboard.press("Space"); await pg.waitForTimeout(100); ok(await pg.isVisible(".gpop"), "Space also opens the card");
  await pg.keyboard.press("Tab"); await pg.waitForTimeout(100);
  const sr = await pg.evaluate(() => { const e = document.querySelector('body > .sr-only'); const b = e.getBoundingClientRect(); return b.width <= 1 && b.height <= 1; });
  ok(sr, "live region is visually hidden");
  await br.close(); console.log(fails ? fails + " FAILED" : "ALL PASS"); process.exit(fails ? 1 : 0); })();
